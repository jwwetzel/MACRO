def test_a_full_build_is_byte_stable(tmp_path):
    """Run it twice, get the same site.

    This is what makes ``build_site.py --check`` mean something and a git
    diff worth reading.  It is also why the chrome footer carries no build
    timestamp: a stamp would make every page differ on every build, and the
    signal would be gone.
    """
    docs = tmp_path / "docs"
    shutil.copytree(DOCS_DIR, docs,
                    ignore=shutil.ignore_patterns("*.png", "*.svg"))
    site.build_site(manifest=None, docs_dir=docs, repo_root=REPO_ROOT)
    first = {p: p.read_bytes() for p in docs.rglob("*.html")}
    site.build_site(manifest=None, docs_dir=docs, repo_root=REPO_ROOT)
    second = {p: p.read_bytes() for p in docs.rglob("*.html")}
    assert first == second


