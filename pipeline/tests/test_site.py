def test_the_content_markers_are_the_same_string_in_both_modules():
    """``provenance`` cannot import ``site`` (``site`` imports it), so the
    markers are declared twice.  They may never drift apart: if they did,
    every published page would look modified to the DAG forever."""
    assert pv.SITE_CONTENT_BEGIN.decode() == site.CONTENT_BEGIN
    assert pv.SITE_CONTENT_END.decode() == site.CONTENT_END


def test_wrapping_a_page_does_not_change_its_provenance_fingerprint(tmp_path):
    """THE POINT OF ``published_content``.

    A stage's output is what the stage wrote.  If re-arranging the furniture
    around a report invalidated the report, every site build would post a
    sweep of STALE verdicts across sixteen stages whose numbers had not
    moved — and a status page that cries stale about everything teaches its
    reader to stop looking.
    """
    _write(tmp_path, "pipeline/s9.html", SAMPLE)
    before = pv.digest_bytes(pv.published_content(SAMPLE.encode()))
    build = _build_for(tmp_path)
    site.wrap_page(build, build.area_by_key[site.PIPELINE],
                   "pipeline/s9.html", ["pipeline/s9.html"])
    after_bytes = (tmp_path / "pipeline/s9.html").read_bytes()
    after = pv.digest_bytes(pv.published_content(after_bytes))
    assert before == after
    # And the raw bytes really did change, so the test is testing something.
    assert pv.digest_bytes(after_bytes) != pv.digest_bytes(SAMPLE.encode())


def test_the_first_wrap_of_a_page_is_free(tmp_path):
    """An unwrapped page hashes to its BODY, not its bytes.

    Without that fallback, the build that first put chrome on a page would
    move its fingerprint once — a one-off sweep of false staleness across
    every published report, which is the same lie as a permanent one, told
    once.  So the artifact is the body either way.
    """
    raw = b"<html><head><title>x</title></head><body>the report</body></html>"
    assert pv.published_content(raw) == b"the report"
    wrapped = (b"<html><head><title>x</title></head><body><nav>chrome</nav>"
               + pv.SITE_CONTENT_BEGIN + b"the report" + pv.SITE_CONTENT_END
               + b"</body></html>")
    assert pv.published_content(wrapped) == b"the report"


def test_something_that_is_not_a_document_is_still_hashed_whole():
    raw = b"target,frames\nSTLMi,812\n"
    assert pv.published_content(raw) == raw


