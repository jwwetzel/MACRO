def test_no_page_is_orphaned_from_the_front_door(pages):
    """Reachability, computed rather than asserted.

    The measured starting point was ONE unreachable page.  The rebuild's
    promise is that there is now no way to produce a second one without a
    test noticing, because the chrome that makes a page reachable is applied
    to every page by the same pass.
    """
    reachable, frontier = {site.LANDING}, [site.LANDING]
    while frontier:
        current = frontier.pop()
        for href in re.findall(r'href="([^"#?]+)', pages.get(current, "")):
            if not href.endswith(".html") or href.startswith("http"):
                continue
            target = site._normalise(
                (Path(current).parent / href).as_posix())
            if target in pages and target not in reachable:
                reachable.add(target)
                frontier.append(target)
    assert set(pages) - reachable == set()


