"""The site assembler, and the guards that keep the navigation honest.

Three kinds of test live here.

The FIRST kind exercises :mod:`macro_core.site` as a module, on synthetic
markup: that a Socratic section is lifted apart correctly, that anchoring and
wrapping are idempotent, that a manuscript skeleton is told apart from a
draft, that relative links come out right at both page depths.

The SECOND kind is the REGRESSION GUARD this file mainly exists for.  The
complaint that produced this module was not "a page is missing"; measured
before the rebuild, exactly one page was unreachable.  It was that a reader
had no sense of place.  So the guards assert PLACE, on the real ``docs/``
tree: every page carries the project row, a breadcrumb and a question rail;
every page is reachable from the front door; no page is a leaf you cannot
climb out of.  A future renderer that emits a page and forgets to let the
assembler see it fails here rather than becoming the next orphan.

The THIRD kind guards the theme.  The site's status colours mean something,
and they mean it in one place — ``docs/assets/macro.css``.  A renderer that
inlines a colour literal is a second stylesheet with no name, and that is
exactly how 85 figures and a dozen table cells ended up styled for a dark
ground that no longer exists.  :func:`test_no_renderer_inlines_a_colour`
closes it.
"""

