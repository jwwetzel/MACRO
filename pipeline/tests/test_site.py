def _build_for(tmp_path: Path) -> site.Build:
    """A Build over a throwaway docs tree, with no manifest behind it."""
    return site.Build(tmp_path, REPO_ROOT, manifest=None)


def test_wrapping_is_idempotent_and_never_nests_chrome(tmp_path):
    """A renderer may re-run at any time, so the assembler has to be able to
    run again on its own output.  Without recovering the original body
    first, the second build would nest chrome inside chrome and the third
    would nest it again."""
    _write(tmp_path, "pipeline/s9.html", SAMPLE)
    build = _build_for(tmp_path)
    area = build.area_by_key[site.PIPELINE]
    site.wrap_page(build, area, "pipeline/s9.html", ["pipeline/s9.html"])
    once = (tmp_path / "pipeline/s9.html").read_text()
    site.wrap_page(build, area, "pipeline/s9.html", ["pipeline/s9.html"])
    twice = (tmp_path / "pipeline/s9.html").read_text()
    assert once == twice
    assert once.count(site.CONTENT_BEGIN) == 1
    assert once.count(site.CONTENT_END) == 1
    assert once.count('class="topbar"') == 1


def test_wrapping_keeps_the_renderers_markup_byte_for_byte(tmp_path):
    _write(tmp_path, "pipeline/s9.html", SAMPLE)
    build = _build_for(tmp_path)
    site.wrap_page(build, build.area_by_key[site.PIPELINE],
                   "pipeline/s9.html", ["pipeline/s9.html"])
    wrapped = (tmp_path / "pipeline/s9.html").read_text()
    recovered = site.original_content(site.page_body(wrapped))
    assert recovered == site.page_body(SAMPLE)


def test_wrapping_adds_the_stylesheet_to_a_page_that_lacked_one(tmp_path):
    """``pipeline_status.html`` links no shared stylesheet — it was written
    to stand alone, because nothing linked to it."""
    _write(tmp_path, "pipeline/loose.html", UNANCHORED)
    build = _build_for(tmp_path)
    site.wrap_page(build, build.area_by_key[site.PIPELINE],
                   "pipeline/loose.html", ["pipeline/loose.html"])
    head = (tmp_path / "pipeline/loose.html").read_text().split("<body")[0]
    assert "../assets/macro.css" in head


def test_prev_and_next_walk_the_evidence_chain(tmp_path):
    for name in ("a", "b", "c"):
        _write(tmp_path, f"pipeline/{name}.html",
               SAMPLE.replace("A Worked Example", f"Page {name.upper()}"))
    build = _build_for(tmp_path)
    siblings = ["pipeline/a.html", "pipeline/b.html", "pipeline/c.html"]
    area = build.area_by_key[site.PIPELINE]
    site.wrap_page(build, area, "pipeline/b.html", siblings)
    middle = (tmp_path / "pipeline/b.html").read_text()
    assert "a.html" in middle and "c.html" in middle
    assert "Previous" in middle and "Next" in middle
    site.wrap_page(build, area, "pipeline/a.html", siblings)
    first = (tmp_path / "pipeline/a.html").read_text()
    assert "Previous" not in first


